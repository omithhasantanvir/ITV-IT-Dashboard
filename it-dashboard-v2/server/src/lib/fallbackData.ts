// Load persisted store from disk if available
function loadPersistedUsers(): FallbackUser[] {
  try {
    if (fs.existsSync(STORE_PATH)) {
      const raw = fs.readFileSync(STORE_PATH, 'utf-8');
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed.users) && parsed.users.length > 0) {
        return parsed.users.map((u: any) => ({
          ...u,
          joiningDate: u.joiningDate ? new Date(u.joiningDate) : null,
          leavingDate: u.leavingDate ? new Date(u.leavingDate) : null,
          createdAt: u.createdAt ? new Date(u.createdAt) : new Date(),
          updatedAt: u.updatedAt ? new Date(u.updatedAt) : new Date(),
        }));
      }
    }
  } catch (err: any) {
    console.warn('Could not read fallbackStore.json:', err.message);
  }
  return defaultAllUsers;
}

export const fallbackUsers: FallbackUser[] = loadPersistedUsers();

