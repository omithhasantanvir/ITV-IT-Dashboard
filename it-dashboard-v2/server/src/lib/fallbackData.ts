// --- 8. Dashboard Summary Generator ---
export function getFallbackDashboardSummary() {
  const totalEmployees = fallbackUsers.length;
  const activeEmployees = fallbackUsers.filter((u) => u.employmentStatus === 'Active').length;
  const formerEmployees = fallbackUsers.filter((u) => u.employmentStatus === 'Former Employee' || u.employmentStatus === 'Former').length;
  const itTeamMembers = fallbackUsers.filter((u) => u.isITTeam && u.employmentStatus === 'Active').length;

  const totalComputers = fallbackComputers.length;
  const assignedComputers = fallbackComputers.filter((c) => c.status === 'ASSIGNED').length;
  const availableComputers = fallbackComputers.filter((c) => c.status === 'AVAILABLE').length;
  const repairComputers = fallbackComputers.filter((c) => c.status === 'REPAIR').length;

  const totalExtensions = fallbackExtensions.length;
  const assignedExtensions = fallbackExtensions.filter((e) => e.status === 'ASSIGNED').length;

  const onlineServers = fallbackServers.filter((s) => s.status === 'ONLINE').length;
  const offlineServers = fallbackServers.filter((s) => s.status === 'OFFLINE').length;
  const warningServers = fallbackServers.filter((s) => s.status === 'WARNING').length;

  const utilizationPercent = totalComputers > 0 ? Math.round((assignedComputers / totalComputers) * 100) : 0;

  const itTeam = fallbackUsers
    .filter((u) => u.isITTeam && u.employmentStatus === 'Active')
    .map((u) => ({
      id: u.id,
      name: u.name,
      designation: u.designation,
      email: u.email,
      phone: u.phone,
      extensionNumber: u.extensionNumber,
      itStatus: u.itStatus,
      profilePhoto: u.profilePhoto,
    }));

  const recentEmployees = fallbackUsers.slice(0, 5).map((u) => ({
    id: u.id,
    name: u.name,
    department: u.department,
    designation: u.designation,
    employmentStatus: u.employmentStatus,
    joiningDate: u.joiningDate,
  }));

  return {
    success: true,
    isFallback: true,
    stats: {
      totalEmployees,
      activeEmployees,
      formerEmployees,
      itTeamMembers,
      totalComputers,
      assignedComputers,
      availableComputers,
      repairComputers,
      totalExtensions,
      assignedExtensions,
      totalServers: fallbackServers.length,
      onlineServers,
      offlineServers,
      warningServers,
    },
    summary: {
      computerStatus: {
        total: totalComputers,
        assigned: assignedComputers,
        available: availableComputers,
        repair: repairComputers,
        utilizationPercent,
      },
      serverStatus: fallbackServers,
      itTeam,
      recentEmployees,
      recentActivities: fallbackActivityLogs,
    },
  };
}
