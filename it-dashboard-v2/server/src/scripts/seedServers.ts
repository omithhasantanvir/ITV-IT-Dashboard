async function main() {
  console.log('Seeding / Upserting 14 Production Servers...');
  for (const srv of servers) {
    const upserted = await prisma.server.upsert({
      where: { serverName: srv.serverName },
      update: srv,
      create: srv,
    });
    console.log(`Upserted: ${upserted.serverName} -> ${upserted.ipAddress}`);
  }
  console.log('Finished seeding 14 production servers.');
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
